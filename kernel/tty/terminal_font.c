static const uint8_t *find_glyph(uint32_t codepoint) {
    size_t first = 0;
    size_t last = sizeof(glyph_map) / sizeof(glyph_map[0]);
    while (first < last) {
        size_t middle = first + (last - first) / 2U;
        if (glyph_map[middle].codepoint < codepoint) first = middle + 1U;
        else last = middle;
    }
    if (first < sizeof(glyph_map) / sizeof(glyph_map[0]) && glyph_map[first].codepoint == codepoint)
        return glyphs[glyph_map[first].glyph];
    return NULL;
}

const uint8_t *tunix_terminal_font_glyph(uint32_t codepoint) {
    const uint8_t *glyph = codepoint <= 0xFFFFU ? find_glyph(codepoint) : NULL;
    if (!glyph) glyph = find_glyph(0xFFFDU);
    if (!glyph) glyph = find_glyph((uint32_t)'?');
    return glyph;
}
