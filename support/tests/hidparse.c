int main(void) {
    struct sample samples[] = {
        { "plain", plain, sizeof(plain), 1, plain_report, sizeof(plain_report), 5, -5, 1, 1, NULL, 0 },
        { "unifying", unifying, sizeof(unifying), 1, unifying_report, sizeof(unifying_report),
          -3, 10, -1, 3, unifying_consumer, sizeof(unifying_consumer) },
        { "gaming", gaming, sizeof(gaming), 1, gaming_report, sizeof(gaming_report), 300, -2, 0, 0x10,
          NULL, 0 },
        { "combo", combo, sizeof(combo), 1, combo_report, sizeof(combo_report), 127, -128, 0, 4,
          combo_keyboard, sizeof(combo_keyboard) },
        { "tablet", tablet, sizeof(tablet), 0, NULL, 0, 0, 0, 0, 0, NULL, 0 },
    };
    int failures = 0;
    for (unsigned index = 0; index < sizeof(samples) / sizeof(samples[0]); index++) {
        struct sample *sample = &samples[index];
        struct hid_mouse_layout layout;
        int parsed = hid_parse_mouse(sample->descriptor, sample->length, &layout) == 0;
        if (parsed != sample->parses) {
            printf("HIDPARSE %s parse=%d expected %d FAIL\n", sample->name, parsed, sample->parses);
            failures++;
            continue;
        }
        if (!parsed) {
            printf("HIDPARSE %s rejected ok\n", sample->name);
            continue;
        }
        int dx, dy, wheel;
        uint32_t buttons;
        int decoded = hid_decode_mouse(&layout, sample->report, sample->report_length, &dx, &dy, &wheel,
                                       &buttons) == 0;
        int ok = decoded && dx == sample->dx && dy == sample->dy && wheel == sample->wheel &&
                 buttons == sample->buttons;
        if (sample->foreign &&
            hid_decode_mouse(&layout, sample->foreign, sample->foreign_length, &dx, &dy, &wheel, &buttons) == 0)
            ok = 0;
        printf("HIDPARSE %s id=%u buttons=%u x=%u/%u y=%u/%u wheel=%u/%u %s\n", sample->name,
               layout.report_id, layout.buttons, layout.x.offset, layout.x.size, layout.y.offset,
               layout.y.size, layout.wheel.offset, layout.wheel.size, ok ? "ok" : "FAIL");
        if (!ok) failures++;
    }
    printf("HIDPARSE %s\n", failures ? "FAIL" : "PASS");
    return failures ? 1 : 0;
}
