#!/bin/sh
# genconfig.sh -- turn Tunix's Kconfig into a .config and a C header.
#
# usage: genconfig.sh <Kconfig> <output-dir> --arch <x86_64|arm64>
#
# Supports the subset of Kconfig the kernel uses today: bool and int
# symbols with constant defaults, and "depends on" clauses. The two *_ARCH
# symbols form the architecture choice: --arch selects exactly one of them
# (and turns the other off), so a stale or empty .config cannot
# desynchronize a build. When <output-dir>/.config is missing it is created
# from the Kconfig defaults; when it exists, its values are kept (and
# validated), merged over the defaults, and re-canonicalized.
#
# Outputs (regenerated idempotently on every run):
#   <output-dir>/.config          canonical .config (in Kconfig order)
#   <output-dir>/kernel_config.h  CONFIG_* defines; the kernel makefiles
#                                 force-include this file (-include ...)
#                                 so every translation unit sees the
#                                 configuration.
set -u

fail() {
    echo "genconfig: $1" >&2
    exit 1
}

[ "${1-}" ] && [ "${2-}" ] && [ "${3-}" = "--arch" ] && [ "${4-}" ] ||
    fail "usage: genconfig.sh <Kconfig> <output-dir> --arch <x86_64|arm64>"
KCONFIG=$1
OUTDIR=$2
ARCH=$4
case "$ARCH" in
x86_64 | arm64) ;;
*) fail "unknown --arch '$ARCH'" ;;
esac
[ -f "$KCONFIG" ] || fail "cannot read Kconfig '$KCONFIG'"

CONFIG="$OUTDIR/.config"
HEADER="$OUTDIR/kernel_config.h"
mkdir -p "$OUTDIR" || fail "cannot create output directory '$OUTDIR'"

# POSIX awk cannot open a missing file: use an empty placeholder instead.
PREV="$OUTDIR/.config.prev"
: >"$PREV"
[ -f "$CONFIG" ] && grep -q . "$CONFIG" 2>/dev/null && PREV="$CONFIG"

awk -v arch="$ARCH" -v cfg_out="$CONFIG" -v hdr_out="$HEADER" '
function bad(msg) { printf "genconfig: %s\n", msg > "/dev/stderr"; exit 1 }
function emit_rec() {
    count++
    sname[count] = name
    stype[count] = type
    sdef[count] = def
    sdep[count] = dep
}

BEGIN { inh = 0 }

FILENAME == ARGV[1] { # pass 1: parse Kconfig (bool/int/depends-on)
    if ($0 ~ /^[[:space:]]*#/) next
    if ($1 == "help") { inh = 1; next }
    if (inh) {
        if (substr($0, 1, 1) ~ /^[ \t]/) next
        inh = 0
    }
    if ($1 == "config" && $2 != "") {
        if (name != "") emit_rec()
        name = $2; type = ""; def = ""; dep = ""
        next
    }
    if (name == "") next
    if ($1 == "bool" || $1 == "int") { type = $1; next }
    if ($1 == "default" && $2 != "") { def = $2; next }
    if ($1 == "depends" && $2 == "on" && $3 != "") { dep = $3; next }
    next
}

FILENAME == ARGV[2] { # pass 2: existing .config values
    line = $0
    sub(/^[ \t]+/, "", line); sub(/[ \t]+$/, "", line)
    if (line == "") next
    if (line ~ /^# [A-Za-z0-9_]+ is not set$/) {
        sym = line
        sub(/^# /, "", sym); sub(/ is not set$/, "", sym)
        sub(/^CONFIG_/, "", sym)
        val[sym] = 0
        next
    }
    if (line ~ /^#/) next
    eq = index(line, "=")
    if (eq <= 1) next
    sym = substr(line, 1, eq - 1)
    v = substr(line, eq + 1)
    sub(/^CONFIG_/, "", sym)
    if (v == "y") val[sym] = 1
    else if (v == "n") val[sym] = 0
    else if (v ~ /^[0-9]+$/) val[sym] = v
    # anything else is ignored here; ints are re-validated below
    next
}

END {
    if (name != "") emit_rec()
    if (count == 0) bad("no config symbols found in " ARGV[1])
    if (arch == "x86_64") { pa = "X86_64_ARCH"; pb = "ARM64_ARCH" }
    else                  { pa = "ARM64_ARCH";  pb = "X86_64_ARCH" }

    # finals[name]: bool -> 1/0; int -> digits; int with unmet dep -> "unset"
    for (i = 1; i <= count; i++) {
        n = sname[i]; t = stype[i]; d = sdef[i]; dp = sdep[i]
        if (t == "bool" && n == pa) { finals[n] = 1; continue }
        if (t == "bool" && n == pb) { finals[n] = 0; continue }
        if (dp != "" && (t == "bool" || t == "int")) {
            if (!(dp in finals)) bad("symbol " n ": depends on [" dp "] which is not defined before it")
            if (finals[dp] == 0) {
                if (t == "bool") finals[n] = 0
                else finals[n] = "unset"
                continue
            }
        }
        if (t == "bool") {
            if (n in val) finals[n] = (val[n] == 1) ? 1 : 0
            else finals[n] = (d == "y") ? 1 : 0
        } else if (t == "int") {
            v = (n in val) ? val[n] : d
            if (v !~ /^[0-9]+$/) bad("symbol " n ": not a decimal int")
            if (v + 0 < 1 || v + 0 > 8192) bad("symbol " n ": value [" v "] out of range 1..8192")
            finals[n] = v
        }
        # unknown type: left unset, so nothing is emitted for it
    }

    # canonical .config, in Kconfig order
    printf "# Tunix .config (generated by tools/genconfig.sh -- do not edit)\n" > cfg_out
    for (i = 1; i <= count; i++) {
        n = sname[i]; t = stype[i]
        if (t == "bool") {
            if (finals[n] == 1) printf "CONFIG_%s=y\n", n > cfg_out
            else printf "# CONFIG_%s is not set\n", n > cfg_out
        } else if (t == "int") {
            if (finals[n] == "unset") printf "# CONFIG_%s is not set (depends on %s)\n", n, sdep[i] > cfg_out
            else if (finals[n] != "") printf "CONFIG_%s=%s\n", n, finals[n] > cfg_out
            else printf "# CONFIG_%s is not recognized (no known type)\n", n > cfg_out
        }
    }
    close(cfg_out)

    # CONFIG_* header, force-included by the kernel makefiles
    printf "/* Generated from Tunix Kconfig by tools/genconfig.sh -- do not edit. */\n" > hdr_out
    printf "#ifndef TUNIX_KERNEL_CONFIG_H\n#define TUNIX_KERNEL_CONFIG_H\n\n" > hdr_out
    for (i = 1; i <= count; i++) {
        n = sname[i]; t = stype[i]; dp = sdep[i]
        if (t == "bool") {
            if (finals[n] == 1) printf "#define CONFIG_%s 1\n", n > hdr_out
            else printf "#undef CONFIG_%s\n", n > hdr_out
        } else if (t == "int") {
            if (finals[n] == "unset") printf "#define CONFIG_%s 1 /* %s is off */\n", n, dp > hdr_out
            else if (finals[n] != "") printf "#define CONFIG_%s %s\n", n, finals[n] > hdr_out
        }
    }
    printf "\n#endif\n" > hdr_out
    close(hdr_out)
}
' "$KCONFIG" "$PREV" || fail "configuration generation failed"

rm -f "$OUTDIR/.config.prev"
exit 0
